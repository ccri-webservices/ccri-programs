#!/usr/bin/env python3
"""
Build the .htaccess redirect block for the workforce programs move.

Reads migration/workforce-move-list.csv and writes
migration/workforce-redirects.htaccess.

Usage:
  python3 migration/build-redirects.py          # R=302 (testing)
  python3 migration/build-redirects.py --301    # R=301 (after launch)

Every rule is guarded by a RewriteCond that checks the OLD file is gone,
so the block can be published before any page moves: each redirect
switches on by itself when its page is moved or deleted in Modern Campus.

Paste the block into the site-root .htaccess ABOVE the generic
"Redirect index pages" rule (RewriteRule ^(.*/|)index\\.html$ ...), which
has [L] and would otherwise catch old folder index pages first.
"""

import csv
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
CSV_PATH = HERE / "workforce-move-list.csv"
OUT_PATH = HERE / "workforce-redirects.htaccess"

# Already handled by an existing .htaccess rule, or not moving
SKIP_ACTIONS = {"stays"}
SKIP_OLD = {"/workforce/programs/CoEmaritime/"}


def esc(path):
    """Escape a literal URL path for a RewriteRule pattern."""
    return re.sub(r"([.+?()\[\]{}^$|*\\])", r"\\\1", path)


def check_safe(url):
    """Targets and paths must not contain characters that need escaping."""
    if re.search(r"[\s%&\\\"']", url):
        sys.exit(f"Unsafe character in {url!r} - fix the CSV")


def rules_for(row, status):
    old, new, action = row["old_url"], row["new_url"], row["action"]
    check_safe(old)
    check_safe(new)
    path = old.lstrip("/")
    flags = f"[R={status},L,NC]"

    if action == "move-file" and old.endswith("/"):
        # A folder of files: redirect each file inside it
        return [
            f"RewriteCond %{{DOCUMENT_ROOT}}/{path}$1 !-f",
            f"RewriteRule ^{esc(path)}(.+)$ {new}$1 {flags}",
        ]
    if action == "move-file":
        return [
            f"RewriteCond %{{DOCUMENT_ROOT}}/{path} !-f",
            f"RewriteRule ^{esc(path)}$ {new} {flags}",
        ]
    if old.endswith("/"):
        # Folder URL: /folder, /folder/, /folder/index.html
        return [
            f"RewriteCond %{{DOCUMENT_ROOT}}/{path}index.html !-f",
            f"RewriteRule ^{esc(path.rstrip('/'))}(/|/index\\.html)?$ {new} {flags}",
        ]
    # Page: with or without .html
    base = path[: -len(".html")] if path.endswith(".html") else path
    return [
        f"RewriteCond %{{DOCUMENT_ROOT}}/{base}.html !-f",
        f"RewriteRule ^{esc(base)}(\\.html)?$ {new} {flags}",
    ]


def main():
    status = 301 if "--301" in sys.argv else 302
    rows = [
        r
        for r in csv.DictReader(CSV_PATH.open())
        if r["action"] not in SKIP_ACTIONS and r["old_url"] not in SKIP_OLD
    ]

    lines = [
        "# ---------------- WORKFORCE PROGRAMS MOVE (Nov 2026) ----------------",
        "# Pages in /workforce/programs/<industry>/ moved to /workforce/programs/.",
        "# Generated by migration/build-redirects.py from workforce-move-list.csv",
        "# in the ccri-programs repo - edit the CSV and regenerate, not by hand.",
        "# Each rule only fires once its old file is gone (RewriteCond ... !-f).",
        f"# Status: {status}" + (" (testing - switch to 301 after launch)" if status == 302 else ""),
    ]
    for row in rows:
        lines.append("")
        lines.append(f"# {row['old_url']}  ({row['action']})")
        lines.extend(rules_for(row, status))
    lines.append("# ---------------- END WORKFORCE PROGRAMS MOVE ----------------")

    OUT_PATH.write_text("\n".join(lines) + "\n")
    rule_count = sum(1 for l in lines if l.startswith("RewriteRule"))
    print(f"Wrote {OUT_PATH.name}: {rule_count} rules, R={status}")


if __name__ == "__main__":
    main()
